const OPERATING_STATES = ['FL', 'GA', 'AL', 'TN', 'SC', 'NC', 'VA'];

// Approximate ZIP ranges per Publix operating state (first 3 digits).
const ZIP_PREFIX_STATE_RANGES: { state: string; min: number; max: number }[] = [
  { state: 'FL', min: 320, max: 349 },
  { state: 'GA', min: 300, max: 319 },
  { state: 'AL', min: 350, max: 369 },
  { state: 'TN', min: 370, max: 385 },
  { state: 'SC', min: 290, max: 299 },
  { state: 'NC', min: 270, max: 289 },
  { state: 'VA', min: 220, max: 246 },
];

export function inferStateFromZip(zip: string): string | null {
  const prefix = parseInt(zip.slice(0, 3), 10);
  if (Number.isNaN(prefix)) return null;
  if (prefix === 201) return 'VA';
  return ZIP_PREFIX_STATE_RANGES.find((r) => prefix >= r.min && prefix <= r.max)?.state ?? null;
}

export function searchStores(zip: string) {
  const zipPrefix = zip.slice(0, 3);

  // Find stores with matching ZIP prefix (first 3 digits for broader results)
  const prefixMatches = PUBLIX_STORES.filter(store =>
    store.zip.startsWith(zipPrefix) &&
    OPERATING_STATES.includes(store.state)
  );
  if (prefixMatches.length > 0) {
    return prefixMatches.slice(0, 10);
  }

  // Fallback: no seed data for this prefix yet — return stores from the
  // inferred state so the form is still usable (e.g. 327xx Orlando area
  // currently has no 327xx seed stores, so FL stores are shown).
  const state = inferStateFromZip(zip);
  if (state) {
    return PUBLIX_STORES.filter((store) => store.state === state).slice(0, 10);
  }

  return [];
}

export function getStoreById(storeId: string) {
  return PUBLIX_STORES.find(store => store.storeId === storeId);
}
